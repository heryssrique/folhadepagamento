function parseRMText(text) {
    const layoutResults = {
        analitico: {
            fields: {
                'PRO LABORE': false, 'Proventos': false, 'Descontos': false,
                'Base FGTS': false, 'Base FGTS 13º': false, 'Base INSS - Envelope': false,
                'Base INSS 13º - Envelope': false, 'INSS': false, 'INSS DIRETOR/AUT': false,
                'INSS 13 SALARIO': false, 'IRRF': false
            }
        }
    };
    let pdfProventos = 0, pdfDescontos = 0, pdfLiquidoFolha = 0, pdfLiquidoPro = 0, pdfAtivos = 0, pdfAfastados = 0, pdfDesligados = 0;
    let pdfBases = { inss: 0, inss13: 0, inssAuton: 0, fgts: 0, fgts13: 0, fgts2: 0, irrf: 0, irrf13: 0, irrfFerias: 0 };
    let pdfEncargos = { inssEmpresa: 0, inssSat: 0, inssTerceiros: 0, inssSatAjustado: 0, inssSegurado: 0, fgtsDep: 0, fgts13Dep: 0 };
    let competencia = '';
    let empresaNome = '';
    let cnpj = '';

    const parseNum = (str) => {
        if (!str) return 0;
        return parseFloat(str.replace(/\./g, '').replace(',', '.')) || 0;
    };

    const lines = text.split('\n');

    lines.forEach(line => {
        const clean = line.trim();

        // 1. Cabeçalho
        if (/Comp:\s*(\d{2}\/\d{4})/i.test(clean)) {
            const m = clean.match(/Comp:\s*(\d{2}\/\d{4})/i);
            if (m) {
                const [mes, ano] = m[1].split('/');
                competencia = `${ano}-${mes}`;
            }
        }
        if (/\d{2}\.\d{3}\.\d{3}\/\d{4}-\d{2}/.test(clean)) {
            const m = clean.match(/\d{2}\.\d{3}\.\d{3}\/\d{4}-\d{2}/);
            if (m) cnpj = m[0];
        }

        // 2. Rubricas / Linhas Individuais (Regex específico para código + descrição + valor)
        // Ex: 1007 PRO LABORE ... 8.475,55
        if (/1007\s+PRO\s+LABORE/i.test(clean) || /PRO[\s-]LABORE/i.test(clean)) {
            const m = clean.match(/1007\s+PRO\s+LABORE\s+\d+\s+[\d,.]+\s+([\d.]+,\d{2})/i);
            if (m) {
                pdfLiquidoPro = parseNum(m[1]);
                layoutResults.analitico.fields['PRO LABORE'] = true;
            }
        }

        // 4016 LIQUIDO FOLHA PAGAMENTO ... 589.840,80
        if (/4016\s+LIQUIDO\s+FOLHA\s+PAGAMENTO/i.test(clean)) {
            const m = clean.match(/4016\s+LIQUIDO\s+FOLHA\s+PAGAMENTO\s+\d+\s+[\d,.]+\s+([\d.]+,\d{2})/i);
            if (m) pdfLiquidoFolha = parseNum(m[1]);
        }

        // 4018 LIQUIDO PAGAMENTO PRO LABORE ... 6.481,86
        if (/4018\s+LIQUIDO\s+PAGAMENTO\s+PRO\s+LABORE/i.test(clean)) {
            const m = clean.match(/4018\s+LIQUIDO\s+PAGAMENTO\s+PRO\s+LABORE\s+\d+\s+[\d,.]+\s+([\d.]+,\d{2})/i);
            if (m && pdfLiquidoPro === 0) pdfLiquidoPro = parseNum(m[1]);
        }

        // 2075 INSS
        if (/2075\s+INSS\b/i.test(clean)) layoutResults.analitico.fields['INSS'] = true;
        // 2080 INSS DIRETOR/AUT
        if (/2080\s+INSS\s+DIRETOR\/AUT/i.test(clean) || /INSS\s+DIRETOR/i.test(clean)) layoutResults.analitico.fields['INSS DIRETOR/AUT'] = true;
        // 2083 INSS 13 SALARIO
        if (/2083\s+INSS\s+13\s+SALARIO/i.test(clean) || /INSS\s+13\s+SAL/i.test(clean)) layoutResults.analitico.fields['INSS 13 SALARIO'] = true;
        // 2110 IRRF
        if (/2110\s+IRRF\b/i.test(clean) || /\bIRRF\b/i.test(clean)) layoutResults.analitico.fields['IRRF'] = true;

        // 3. Totais e Bases nos Blocos de 3 Colunas:
        // Proventos
        const mProv = clean.match(/^Proventos\s+([\d.]+,\d{2})/i) || clean.match(/\bProventos\s+([\d.]+,\d{2})/i);
        if (mProv) {
            pdfProventos = parseNum(mProv[1]);
            layoutResults.analitico.fields['Proventos'] = true;
        }

        // Descontos
        const mDesc = clean.match(/\bDescontos\s+([\d.]+,\d{2})/i);
        if (mDesc) {
            pdfDescontos = parseNum(mDesc[1]);
            layoutResults.analitico.fields['Descontos'] = true;
        }

        // Líquido (Totais)
        const mLik = clean.match(/\bL[íi]quido\s+([\d.]+,\d{2})/i);
        if (mLik && pdfLiquidoFolha === 0) {
            pdfLiquidoFolha = parseNum(mLik[1]);
        }

        // Base INSS - Envelope
        const mInssEnv = clean.match(/Base\s+INSS\s*[-–]?\s*Envelope\s+([\d.]+,\d{2})/i);
        if (mInssEnv) {
            pdfBases.inss = parseNum(mInssEnv[1]);
            layoutResults.analitico.fields['Base INSS - Envelope'] = true;
        }

        // Base INSS 13º - Envelope
        const mInss13Env = clean.match(/Base\s+INSS\s+13[°º]?\s*[-–]?\s*Envelope\s+([\d.]+,\d{2})/i);
        if (mInss13Env) {
            pdfBases.inss13 = parseNum(mInss13Env[1]);
            layoutResults.analitico.fields['Base INSS 13º - Envelope'] = true;
        }

        // Base INSS Auton.
        const mInssAut = clean.match(/Base\s+INSS\s+Auton\.?\s+([\d.]+,\d{2})/i);
        if (mInssAut) pdfBases.inssAuton = parseNum(mInssAut[1]);

        // Base FGTS
        const mFgts = clean.match(/^Base\s+FGTS\s+([\d.]+,\d{2})/i);
        if (mFgts) {
            pdfBases.fgts = parseNum(mFgts[1]);
            layoutResults.analitico.fields['Base FGTS'] = true;
        }

        // Base FGTS 13º
        const mFgts13 = clean.match(/^Base\s+FGTS\s+13[°º]?\s+([\d.]+,\d{2})/i);
        if (mFgts13) {
            pdfBases.fgts13 = parseNum(mFgts13[1]);
            layoutResults.analitico.fields['Base FGTS 13º'] = true;
        }

        // Base FGTS Menor Apr.(SEFIP)
        const mFgts2 = clean.match(/Base\s+FGTS\s+Menor\s+Apr\.?\(SEFIP\)\s+([\d.]+,\d{2})/i);
        if (mFgts2) pdfBases.fgts2 = parseNum(mFgts2[1]);

        // Base IRRF
        const mIrrf = clean.match(/\bBase\s+IRRF\s+([\d.]+,\d{2})/i);
        if (mIrrf) pdfBases.irrf = parseNum(mIrrf[1]);

        // Base IRRF 13º
        const mIrrf13 = clean.match(/\bBase\s+IRRF\s+13[°º]?\s+([\d.]+,\d{2})/i);
        if (mIrrf13) pdfBases.irrf13 = parseNum(mIrrf13[1]);

        // Base IRRF Férias
        const mIrrfFer = clean.match(/\bBase\s+IRRF\s+F[ée]rias\s+([\d.]+,\d{2})/i);
        if (mIrrfFer) pdfBases.irrfFerias = parseNum(mIrrfFer[1]);

        // INSS Detalhado
        const mInssEmp = clean.match(/INSS\s+Empresa\s+([\d.]+,\d{2})/i);
        if (mInssEmp) pdfEncargos.inssEmpresa = parseNum(mInssEmp[1]);

        const mInssSat = clean.match(/INSS\s+SAT\s+([\d.]+,\d{2})/i);
        if (mInssSat) pdfEncargos.inssSat = parseNum(mInssSat[1]);

        const mInssSatAj = clean.match(/INSS\s+SAT\s+Ajustado\s+([\d.]+,\d{2})/i);
        if (mInssSatAj) pdfEncargos.inssSatAjustado = parseNum(mInssSatAj[1]);

        const mInssTerc = clean.match(/INSS\s+Terceiro\s+([\d.]+,\d{2})/i);
        if (mInssTerc) pdfEncargos.inssTerceiros = parseNum(mInssTerc[1]);

        const mInssSeg = clean.match(/INSS\s+Segurado\s+([\d.]+,\d{2})/i);
        if (mInssSeg) pdfEncargos.inssSegurado = parseNum(mInssSeg[1]);

        // FGTS Depositado
        const mFgtsDep = clean.match(/^FGTS\s+Dep\.\s+([\d.]+,\d{2})/i);
        if (mFgtsDep) pdfEncargos.fgtsDep = parseNum(mFgtsDep[1]);

        const mFgts13Dep = clean.match(/^FGTS\s+13[°º]?\s+Dep\.\s+([\d.]+,\d{2})/i);
        if (mFgts13Dep) pdfEncargos.fgts13Dep = parseNum(mFgts13Dep[1]);

        // 4. Quadro de Funcionários:
        // Total de Funcionários:                 238   Ativos:                                216   Demitidos:                              15
        if (/Total\s+de\s+Funcion[áa]rios:/i.test(clean)) {
            const mTot = clean.match(/Total\s+de\s+Funcion[áa]rios:\s+(\d+)/i);
            const mAtv = clean.match(/Ativos:\s+(\d+)/i);
            const mDem = clean.match(/Demitidos:\s+(\d+)/i);
            if (mAtv) pdfAtivos = parseInt(mAtv[1]);
            else if (mTot) pdfAtivos = parseInt(mTot[1]);
            if (mDem) pdfDesligados = parseInt(mDem[1]);
        }
        if (/Af\.\s+Previd[êe]ncia:\s+(\d+)/i.test(clean)) {
            const mAf = clean.match(/Af\.\s+Previd[êe]ncia:\s+(\d+)/i);
            if (mAf) pdfAfastados += parseInt(mAf[1]);
        }
        if (/Af\.\s+Ac\.\s+Trabalho:\s+(\d+)/i.test(clean)) {
            const mAc = clean.match(/Af\.\s+Ac\.\s+Trabalho:\s+(\d+)/i);
            if (mAc) pdfAfastados += parseInt(mAc[1]);
        }
    });

    console.log('Resultados do Parsing RM Labore:');
    console.log('Competencia:', competencia);
    console.log('CNPJ:', cnpj);
    console.log('Proventos:', pdfProventos);
    console.log('Descontos:', pdfDescontos);
    console.log('Liquido Folha:', pdfLiquidoFolha);
    console.log('Liquido Pro Labore:', pdfLiquidoPro);
    console.log('Ativos:', pdfAtivos, 'Afastados:', pdfAfastados, 'Desligados:', pdfDesligados);
    console.log('Bases:', pdfBases);
    console.log('Encargos:', pdfEncargos);
    console.log('Layout Results:', layoutResults);
}

parseRMText(sampleText);
